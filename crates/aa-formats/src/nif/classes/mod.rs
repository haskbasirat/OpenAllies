pub(crate) type LoadFn = fn(&mut Stream, &mut Fields) -> Result<(), NifError>;

pub(crate) struct Class {
    pub registered: &'static str,
    pub name: &'static str,
    /// The native create function (documentation and audit only).
    #[allow(dead_code)]
    pub create: u32,
    pub load: Option<LoadFn>,
}

