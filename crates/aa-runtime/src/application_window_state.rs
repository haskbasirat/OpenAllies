//! The retained application+34 word (static B396C4), not GameAppState.mode.
//!41781A initializes it to zero.40DAC0/40DA30 change it before their timer,
//!capture/input and diagnostic effects. This module ports that word prefix
//!only and returns the reached transition; it does not port those effects.
//!
//!One window-thread writer owns State. Readers retain the same allocation;
//!they cannot assign flags or cache a per-frame gate snapshot.
use std::sync::{
    Arc, Mutex,
    atomic::{AtomicU32, Ordering},
};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Transition {
    None,
    Activated,
    Deactivated,
}

pub struct ApplicationWindowState {
    flags: Arc<AtomicU32>,
    observation_error: Arc<Mutex<Option<String>>>,
}
#[derive(Clone)]
pub struct Reader {
    flags: Arc<AtomicU32>,
    observation_error: Arc<Mutex<Option<String>>>,
}
impl ApplicationWindowState {
    ///41781A, after actual App constructor reaches its +34 initialization.
    pub fn from_native_constructor() -> Self {
        Self {
            flags: Arc::new(AtomicU32::new(0)),
            observation_error: Arc::new(Mutex::new(None)),
        }
    }
    pub fn reader(&self) -> Reader {
        Reader {
            flags: Arc::clone(&self.flags),
            observation_error: Arc::clone(&self.observation_error),
        }
    }
    pub fn flags_b396c4(&self) -> Result<u32, String> {
        self.reader().flags_b396c4()
    }
    ///Backend availability metadata, not native flag bits. If an OS observer
    ///loses its real HWND, future lazy reads must refuse stale focused flags.
    ///Only the window-thread writer can publish/clear this observation error.
    pub fn observation_result(&mut self, result: Result<(), String>) -> Result<(), String> {
        *self
            .observation_error
            .lock()
            .map_err(|_| "window observation owner is poisoned")? = result.err();
        Ok(())
    }
    ///40DAC0..40DAF4, stopping before the transition diagnostic/effects.
    ///The original routine promotes exactly mask2 to3, not every mask with bit1.
    pub fn activate(&mut self, mut mask: u32) -> Transition {
        let old = self.flags.load(Ordering::Acquire);
        if mask == 2 {
            mask = 3;
        }
        if old & mask == mask {
            return Transition::None;
        }
        //Native reread at40DAE0. There is one window-thread writer and no
        //callback between these reads; simulation readers cannot mutate it.
        let new = self.flags.load(Ordering::Acquire) | mask;
        self.flags.store(new, Ordering::Release);
        if old & 2 == 0 && new & 2 != 0 {
            Transition::Activated
        } else {
            Transition::None
        }
    }
    ///40DA30..40DA57, stopping before the transition diagnostic/effects.
    pub fn deactivate(&mut self, mask: u32) -> Transition {
        let old = self.flags.load(Ordering::Acquire);
        if old & mask == 0 {
            return Transition::None;
        }
        let new = old & !mask;
        self.flags.store(new, Ordering::Release);
        if old & 2 != 0 && new & 2 == 0 {
            Transition::Deactivated
        } else {
            Transition::None
        }
    }
    ///6FD538..6FD5A1: native WM_ACTIVATE's low/high words.
    pub fn window_activate(&mut self, wparam: u32) -> Transition {
        if wparam as u16 != 0 && wparam >> 16 == 0 {
            self.activate(2)
        } else {
            self.deactivate(2)
        }
    }
    ///6FD4ED..6FD533/6FD59C: native WM_ACTIVATEAPP.
    pub fn activate_app(&mut self, active: bool) -> Transition {
        if active {
            self.activate(1)
        } else {
            self.deactivate(1)
        }
    }
}
impl Reader {
    ///A fresh read of the sole retained process word at each native gate.
    pub fn flags_b396c4(&self) -> Result<u32, String> {
        if let Some(error) = self
            .observation_error
            .lock()
            .map_err(|_| "window observation owner is poisoned")?
            .as_ref()
        {
            return Err(error.clone());
        }
        Ok(self.flags.load(Ordering::Acquire))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn native_window_word_prefixes() {
        //Generated by the original/v14 paired Unicorn producer. Each sequence
        //starts at the actual constructor-zero domain, with arbitrary masks.
        let rows: &[(u32, bool, u32, u32, u8)] = include!(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../research/skirmish-20261017-window-focus/native-focus-rows.rs"
        ));
        for &(before, activate, mask, after, transition) in rows {
            let mut state = ApplicationWindowState::from_native_constructor();
            //Populate arbitrary test inputs through the real word writer.
            if before != 0 {
                state.activate(before);
            }
            //Mask2 promotes to3; produce its exact test domain by clearing1.
            if before == 2 {
                state.deactivate(1);
            }
            assert_eq!(state.flags_b396c4().unwrap(), before);
            let reader = state.reader();
            let result = if activate {
                state.activate(mask)
            } else {
                state.deactivate(mask)
            };
            assert_eq!(reader.flags_b396c4().unwrap(), after);
            assert_eq!(
                result,
                match transition {
                    0 => Transition::None,
                    1 => Transition::Activated,
                    2 => Transition::Deactivated,
                    _ => panic!("bad native transition"),
                }
            );
        }
    }
    #[test]
    fn same_reader_tracks_focus_and_minimize_events() {
        let mut state = ApplicationWindowState::from_native_constructor();
        let reader = state.reader();
        assert_eq!(reader.flags_b396c4().unwrap(), 0);
        state.observation_result(Err("HWND lost".into())).unwrap();
        assert_eq!(reader.flags_b396c4().unwrap_err(), "HWND lost");
        state.observation_result(Ok(())).unwrap();
        assert_eq!(reader.flags_b396c4().unwrap(), 0);
        assert_eq!(state.activate_app(true), Transition::None);
        assert_eq!(state.window_activate(1), Transition::Activated);
        assert_eq!(reader.flags_b396c4().unwrap(), 3);
        assert_eq!(state.window_activate(0x10001), Transition::Deactivated);
        assert_eq!(reader.flags_b396c4().unwrap(), 1);
        state.activate_app(false);
        assert_eq!(reader.flags_b396c4().unwrap(), 0);
    }
}
