"""Generate crates/aa-orders/src/flow_table.rs from order-flow.json.

Each Shape field is read off the ORIGINAL handler's recorded behaviour:
  request          descriptor role (registration name)
  decree           9-bit id written to admin+0x1F8 in the accepted case
  version_check    'version_not_acked' case rejected with line 0x118
  film_check       'film_session' case rejected with line 0x11C
  validity         static: inline cheat permission (24..29) or a member
                   function found between 0x766C70 and 0x766CA0
  s_log            the handler contains the S-synchronizer string log 0x40F950
                   (runtime-suppressed only for TGC_SetPlayerOrderDecree)
  mirror           the accepted/executed case queries 0x766C50
  trailing_bits_log the accepted case logs "o.GetBitSize()" after processing
                   (or, for PlayerJoin where the runtime check suppresses it,
                   the handler contains the second 0x77DA70 call)
  process          static process call (see static-handler-calls.json)
"""
from pathlib import Path
import json
HERE = Path(__file__).resolve().parent; ROOT = HERE.parents[1]
CHEATS = set(range(24, 30))

def main():
    flow = json.loads((HERE / 'order-flow.json').read_text())
    static = {r['id']: r for r in json.loads((HERE / 'static-handler-calls.json').read_text())}
    rows = []
    for d in flow['descriptors']:
        i = d['id']; s = static[i]; cases = {c['config']: c for c in d['cases']}
        request = d['name'].endswith('Request')
        acc = cases['accepted' if request else 'executed']
        ev = acc['events']
        writes = [e for e in ev if e['kind'] == 'write' and e['stream'] == 'decree']
        if request:
            decree = writes[0]['value'] if writes else None
        else:
            decree = i
        def rejected(name, line):
            c = cases.get(name)
            return bool(c) and any(e['kind'] == 'rejected' and e['line'] == line for e in c['events'])
        validity = 'Validity::None'
        if i in CHEATS: validity = 'Validity::CheatsEnabled'
        elif s.get('validity'): validity = f"Validity::Function({s['validity'][0]})"
        bits_logs = [e for e in ev if e['kind'] == 'sync_int' and e['label'] == 'o.GetBitSize()']
        trailing = len(bits_logs) >= 2 or (request and decree == 317 and s['calls'].count('0x77da70') >= 3)
        proc = s.get('process')
        proc_va = proc if isinstance(proc, str) and proc.startswith('0x') else '0'
        rows.append((i, decree if decree is not None else i, request, rejected('version_not_acked', 0x118),
                     rejected('film_session', 0x11c), validity, '0x40f950' in s['calls'],
                     any(e['kind'] == 'mirror_query' for e in ev), trailing, proc_va, decree is None))
    out = ['// Generated by research/phase8-orders/gen_flow_table.py from order-flow.json',
           '// (original handler behaviour). Do not edit by hand.',
           f'pub static SHAPES: [Shape; {len(rows)}] = [']
    for i, decree, request, ver, film, validity, slog, mirror, trailing, proc, nodecree in rows:
        note = '  // request handler wrote no decree in the recorded case' if nodecree else ''
        out.append(f'    Shape {{ descriptor: {i}, decree: {decree}, request: {str(request).lower()}, version_check: {str(ver).lower()}, '
                   f'film_check: {str(film).lower()}, validity: {validity}, s_log: {str(slog).lower()}, mirror: {str(mirror).lower()}, '
                   f'trailing_bits_log: {str(trailing).lower()}, process: {proc} }},{note}')
    out.append('];')
    (ROOT / 'crates/aa-orders/src/flow_table.rs').write_text('\n'.join(out) + '\n')
    print(len(rows), 'shapes;', sum(r[-1] for r in rows), 'requests without decree')

if __name__ == '__main__':
    main()
