"""Emit Rust builtin tables from the actual native registration/schema capture."""
from pathlib import Path
import json,subprocess
HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[1];r=json.loads((HERE/'native-registrations.json').read_text())
lines=['// Generated by research/phase7-triggers/generate_registrations.py.','// Values come from actual original registration and schema initialization.','pub fn element(name: &str) -> Option<u32> {','match name.to_ascii_lowercase().as_str() {']
for x in r['elements']:lines.append(f'"{x["name"]}" => Some({x["index"]}),')
lines+=['_ => None,','}}','pub fn item(name: &str) -> Option<(u32, u32)> {','match name.to_ascii_lowercase().as_str() {']
for x in r['items']:lines.append(f'"{x["name"]}" => Some(({x["index"]}, {x["storage"]})),')
lines+=['_ => None,','}}','pub fn argument(name: &str) -> Option<u32> {','match name.to_ascii_lowercase().as_str() {']
for x in r['arguments']:lines.append(f'"{x["name"]}" => Some({x["index"]}),')
lines+=['_ => None,','}}','pub fn schema(opcode: u32) -> Option<(u32, &\'static [u32])> {','match opcode {']
for x in r['element_schemas']:lines.append(f'{x["opcode"]} => Some(({x["kind"]}, &{x["arguments"]})),')
lines+=['_ => None,','}}']
path=ROOT/'crates/aa-triggers/src/registrations.rs';path.write_text('\n'.join(lines)+'\n');subprocess.run(['rustfmt','--edition','2024',str(path)],check=True)
